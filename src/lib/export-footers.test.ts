import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { INVOICE_FOOTER_TEXT } from "@/lib/invoices/invoice-branding";
import { generateTaxComputationHTML } from "@/lib/financial-statements/tax-computation-html";
import { generatePITFormHTML } from "@/lib/nrs-filing/form-generator";
import { generateVATForm } from "@/lib/nrs-forms";

const jsPdfApi = jsPDF as unknown as {
  API: { autoTable?: (options: unknown) => jsPDF };
};
if (!jsPdfApi.API.autoTable) {
  jsPdfApi.API.autoTable = function (this: jsPDF, options: unknown) {
    autoTable(this, options as Parameters<typeof autoTable>[1]);
    return this;
  };
}

const files = [
  "src/lib/export-service.ts",
  "src/lib/financial-statements/tax-computation-html.ts",
  "src/lib/nrs-filing/form-generator.ts",
  "src/lib/nrs-forms.ts",
  "src/lib/invoices/invoice-pdf.ts",
  "src/lib/pdf-generator.ts",
];

describe("IVA-191 export footers", () => {
  it("keeps Powered by Kompleet as the shared footer line", () => {
    expect(INVOICE_FOOTER_TEXT).toBe("Powered by Kompleet");
  });

  it("does not say Generated by KOMPLEET Platform on PDF or HTML exports", () => {
    for (const rel of files) {
      const text = readFileSync(resolve(process.cwd(), rel), "utf8");
      expect(text, rel).not.toMatch(/Generated by KOMPLEET Platform/);
    }
  });

  it("uses the shared footer on tax and NRS exports", () => {
    for (const rel of [
      "src/lib/export-service.ts",
      "src/lib/financial-statements/tax-computation-html.ts",
      "src/lib/nrs-filing/form-generator.ts",
      "src/lib/nrs-forms.ts",
    ]) {
      const text = readFileSync(resolve(process.cwd(), rel), "utf8");
      expect(text, rel).toMatch(/INVOICE_FOOTER_TEXT/);
      expect(text, rel).not.toMatch(/Kompleet records\. Kompleet filings/);
    }
  });

  it("uses a comma in the PIT subtitle", () => {
    const text = readFileSync(resolve(process.cwd(), "src/lib/nrs-filing/form-generator.ts"), "utf8");
    expect(text).toContain("Nigeria Revenue Service (NRS), Form PIT-001");
    expect(text).not.toContain("Nigeria Revenue Service (NRS) - Form PIT-001");
  });

  it("prints tax computation section headers in dark ink on grey", () => {
    const text = readFileSync(
      resolve(process.cwd(), "src/lib/financial-statements/tax-computation-html.ts"),
      "utf8",
    );
    const block = text.match(/\.section-header\s*\{[^}]+\}/);
    expect(block?.[0]).toMatch(/color:\s*#333/);
    expect(block?.[0]).not.toMatch(/color:\s*white/);
  });

  it("drops Legal References and keeps the tax computation schedule black and grey", () => {
    const html = generateTaxComputationHTML({
      accountingProfit: 4_500_000,
      taxAdjustments: {
        addBack: { "Disallowed expenses": 120_000 },
        deductions: { "Capital allowances": 80_000 },
      },
      taxableIncome: 4_540_000,
      taxRate: 30,
      taxLiability: 1_362_000,
    });
    expect(html).toContain("Tax Computation Schedule");
    expect(html).toContain("ADD BACK: Non-Deductible Expenses");
    expect(html).toContain("LESS: Allowable Deductions");
    expect(html).toContain("Taxable Income");
    expect(html).toContain("Tax Liability");
    expect(html).toContain(INVOICE_FOOTER_TEXT);
    expect(html).not.toMatch(/Legal References/);
    expect(html).not.toMatch(/Nigeria Tax Act/);
    expect(html).not.toMatch(/#1a5f3a|#e8f5e9|#10b981/i);
    expect(html).toMatch(/color:\s*#000000/);
    expect(html).toMatch(/background:\s*#ffffff/);
  });

  it("prints the PIT form with a dark ink title and grey highlights, no green", () => {
    const html = generatePITFormHTML({
      taxpayerName: "Ada Okonkwo",
      tin: "12345678-0001",
      taxYear: 2026,
      grossIncome: 4_500_000,
      allowableDeductions: 500_000,
      taxableIncome: 4_000_000,
      taxLiability: 412_500,
      taxPaid: 50_000,
      taxDue: 362_500,
    });
    const pitCss = html.slice(0, html.indexOf("</style>"));
    expect(pitCss).toMatch(/h1\s*\{[^}]*color:\s*#000000/);
    expect(pitCss).toMatch(/background-color:\s*#F3F3F3/);
    expect(pitCss).not.toMatch(/#1a5f3a|#e8f5e9|#10b981/i);
    expect(html).toContain("Nigeria Revenue Service (NRS), Form PIT-001");
    expect(pitCss).toMatch(/\.form-value\s*\{[^}]*white-space:\s*nowrap/);
    expect(pitCss).toMatch(/\.form-label\s*\{[^}]*padding-right:\s*12px/);
    expect(html).toMatch(/class="keep">\(1&nbsp;−&nbsp;2\)/);
    expect(html).toMatch(/class="keep">\(4&nbsp;−&nbsp;5\)/);
  });

  it("VAT return PDF contains no Tax Act wording", () => {
    const pdf = generateVATForm({
      businessName: "Ada Foods Ltd",
      tin: "12345678-0001",
      address: "14 Marina Road, Lagos",
      phone: "+234 801 234 5678",
      email: "ada@adafoods.ng",
      period: "October 2026",
      taxYear: 2026,
      outputVAT: 75_000,
      inputVAT: 15_000,
      netVAT: 60_000,
      penaltyIfAny: 0,
      totalDue: 60_000,
    });
    const out = pdf.output();
    expect(out).toContain("VAT returns must be filed within 21 days");
    expect(out).not.toMatch(/Tax Act/i);
    expect(out).not.toContain("Late filing attracts penalties");
    expect(out).not.toContain("Late filing may attract penalties");
  });

  it("VAT return PDF table header uses Amount (NGN) and no naira glyph", () => {
    const pdf = generateVATForm({
      businessName: "Ada Foods Ltd",
      tin: "12345678-0001",
      address: "14 Marina Road, Lagos",
      phone: "+234 801 234 5678",
      email: "ada@adafoods.ng",
      period: "October 2026",
      taxYear: 2026,
      outputVAT: 75_000,
      inputVAT: 15_000,
      netVAT: 60_000,
      penaltyIfAny: 0,
      totalDue: 60_000,
    });
    const out = pdf.output();
    const text = out.replace(/\\([()])/g, "$1");
    expect(text).toContain("Amount (NGN)");
    expect(text).not.toContain("₦");
    expect(text).not.toContain("¦");
  });
});
