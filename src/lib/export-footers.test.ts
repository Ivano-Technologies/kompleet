import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { INVOICE_FOOTER_TEXT } from "@/lib/invoices/invoice-branding";

const files = [
  "src/lib/export-service.ts",
  "src/lib/financial-statements/tax-computation-html.ts",
  "src/lib/nrs-filing/form-generator.ts",
  "src/lib/nrs-forms.ts",
  "src/lib/invoices/invoice-pdf.ts",
  "src/lib/pdf-generator.ts",
];

describe("IVA-191 export footers", () => {
  it("keeps Powered by Kompleet as the shared footer line", () => {
    expect(INVOICE_FOOTER_TEXT).toBe("Powered by Kompleet");
  });

  it("does not say Generated by KOMPLEET Platform on PDF or HTML exports", () => {
    for (const rel of files) {
      const text = readFileSync(resolve(process.cwd(), rel), "utf8");
      expect(text, rel).not.toMatch(/Generated by KOMPLEET Platform/);
    }
  });

  it("uses the shared footer on tax and NRS exports", () => {
    for (const rel of [
      "src/lib/export-service.ts",
      "src/lib/financial-statements/tax-computation-html.ts",
      "src/lib/nrs-filing/form-generator.ts",
      "src/lib/nrs-forms.ts",
    ]) {
      const text = readFileSync(resolve(process.cwd(), rel), "utf8");
      expect(text, rel).toMatch(/INVOICE_FOOTER_TEXT/);
      expect(text, rel).not.toMatch(/Kompleet records\. Kompleet filings/);
    }
  });
});
