function crc32(buf: Buffer): number {
  let c: number;
  let crc = 0xffffffff;
  for (let n = 0; n < buf.length; n++) {
    c = (crc ^ buf[n]!) & 0xff;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

/** Minimal solid grey RGB PNG. */
function png(width: number, height: number): Uint8Array {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  const raw = Buffer.alloc((width * 3 + 1) * height, 0x80);
  for (let y = 0; y < height; y++) raw[y * (width * 3 + 1)] = 0;
  return new Uint8Array(
    Buffer.concat([
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
      chunk("IHDR", ihdr),
      chunk("IDAT", deflateSync(raw)),
      chunk("IEND", Buffer.alloc(0)),
    ]),
  );
}

function base(sender: InvoicePdfInput["sender"], logo: InvoicePdfInput["logo"] = null): InvoicePdfInput {
  return {
    invoiceNumber: "INV-2026-0001",
    invoiceDate: "2026-10-17",
    dueDate: "2026-10-31",
    taxYear: 2026,
    customer: { name: "Bola Stores", address: "2 Allen Avenue\nIkeja, Lagos" },
    sender,
    lineItems: [{ description: "Catering", quantity: 2, unit_price: 50000, vat_rate: 0, amount: 100000 }],
    subtotal: 100000,
    vatAmount: 0,
    discountAmount: 0,
    totalAmount: 100000,
    logo,
  };
}

const text = (input: InvoicePdfInput) => renderInvoicePdf(input).output();

describe("IVA-185 invoice PDF", () => {
  it("footer is one line: Powered by Kompleet, with no NRS claim or tagline", () => {
    const out = text(base({ name: "Ada Foods Ltd" }));
    expect(out).toContain("Powered by Kompleet");
    expect(out).not.toMatch(/NRS/);
    expect(out).not.toMatch(/FIRS/);
    expect(out).not.toMatch(/Generated by/);
    expect(out).not.toMatch(/Kompleet records/);
    expect(out).not.toMatch(/Scan to verify/);
  });

  it("never prints KOMPLEET as the sender", () => {
    expect(text(base({ name: "Ada Foods Ltd" }))).not.toContain("KOMPLEET");
    expect(text(base({ name: "" }))).not.toContain("KOMPLEET");
  });

  it("name only prints the business name", () => {
    expect(text(base({ name: "Ada Foods Ltd" }))).toContain("Ada Foods Ltd");
  });

  it("no name prints the neutral placeholder", () => {
    expect(text(base({ name: "" }))).toContain("Your business name");
  });

  it("logo plus name embeds the image and prints the name", () => {
    const data = png(64, 64);
    const out = text(base({ name: "Ada Foods Ltd" }, { data, format: "PNG", width: 64, height: 64 }));
    expect(out).toContain("/Subtype /Image");
    expect(out).toContain("Ada Foods Ltd");
  });

  it("wide logo embeds the image and leaves the name out", () => {
    const data = png(400, 100);
    const out = text(base({ name: "Ada Foods Ltd" }, { data, format: "PNG", width: 400, height: 100 }));
    expect(out).toContain("/Subtype /Image");
    expect(out).not.toContain("Ada Foods Ltd");
  });

  it("draws the Ivano mark in #000 and #555 only, not slate", () => {
    const out = text(base({ name: "Ada Foods Ltd" }));
    // jsPDF writes greys as a single "g" value: 0 g for #000, 0.333 g for #555.
    expect(out).toMatch(/\b0\.333 g\b/);
    expect(out).not.toMatch(/0\.361 0\.4 0\.451 rg/); // #5C6673
    expect(out).not.toMatch(/0\.078 0\.106 0\.149 rg/); // #141B26
  });

  it("has no green band or colour fills", () => {
    const out = text(base({ name: "Ada Foods Ltd" }));
    // #0A6847 as PDF rgb fill: 0.039 0.408 0.278
    expect(out).not.toMatch(/0\.039\d* 0\.408\d* 0\.278\d* rg/);
  });
});

describe("IVA-185 logo bytes", () => {
  it("reads PNG size", () => {
    expect(sniffImage(png(300, 120))).toEqual({ type: "image/png", width: 300, height: 120 });
  });

  it("rejects non images", () => {
    expect(sniffImage(new TextEncoder().encode("<svg onload=alert(1)>"))).toBeNull();
  });

  it("only fetches logos from Convex storage over https", () => {
    expect(isAllowedLogoUrl("https://shiny-cricket-316.convex.cloud/api/storage/x")).toBe(true);
    expect(isAllowedLogoUrl("http://shiny-cricket-316.convex.cloud/api/storage/x")).toBe(false);
    expect(isAllowedLogoUrl("https://169.254.169.254/latest")).toBe(false);
  });
});

describe("IVA-185 PDF line amounts", () => {
  const legacy = (discount?: number): InvoicePdfInput => ({
    ...base({ name: "Ada Foods Ltd" }),
    lineItems: [
      // Older full form data stored the amount including VAT.
      { description: "Catering", quantity: 1, unit_price: 850000, vat_rate: 7.5, amount: 913750, discount },
      { description: "Delivery", quantity: 2, unit_price: 25000, vat_rate: 0, amount: 50000 },
    ],
    subtotal: 900000 - (discount ?? 0),
    vatAmount: 63750,
    totalAmount: 963750,
  });

  it("prints the pre-VAT amount, so rows add up to the subtotal", () => {
    const out = text(legacy());
    expect(out).toContain("NGN 850,000.00");
    expect(out).not.toContain("913,750.00");
    expect(out).toContain("NGN 900,000.00");
  });

  it("hides the Discount column when no line has a discount", () => {
    expect(text(legacy())).not.toContain("Discount");
    const withDiscount = text(legacy(10000));
    expect(withDiscount).toContain("Discount");
    expect(withDiscount).toContain("NGN 840,000.00");
  });
});

describe("IVA-185 PDF totals and discount", () => {
  const lines = (discount?: number): InvoicePdfInput => ({
    ...base({ name: "Ada Foods Ltd" }),
    lineItems: [
      { description: "Consulting", quantity: 1.5, unit_price: 33.33, vat_rate: 0, amount: 0 },
      { description: "Consulting", quantity: 1.5, unit_price: 33.33, vat_rate: 0, amount: 0, discount },
    ],
    // Stale stored totals: the PDF must rebuild them from the lines.
    subtotal: 99.99,
    vatAmount: 0,
    totalAmount: 99.99,
    discountAmount: discount ?? 0,
  });

  it("Subtotal is the sum of the printed rows", () => {
    const out = text(lines());
    expect(out).toContain("NGN 50.00");
    expect(out).toContain("NGN 100.00");
    expect(out).not.toContain("99.99");
  });

  it("shows discounts only as a column, never as a totals row", () => {
    const out = text(lines(9.99));
    expect(out.match(/\(Discount\)/g)?.length).toBe(1);
    expect(out).toContain("NGN 9.99");
    expect(out).toContain("NGN 40.01");
    expect(out).toContain("NGN 90.01");
    expect(text(lines())).not.toContain("Discount");
  });

  it("clamps a discount larger than the line total", () => {
    const out = text(lines(500));
    // Line 2 is 50.00 gross (49.995 half-up), so the discount clamps to 50.00 and the line to 0.00.
    expect(out).toContain("NGN 0.00");
    expect(out).toContain("NGN 50.00");
    expect(out).not.toContain("500.00");
  });
});

describe("IVA-185 PDF VAT rate format", () => {
  it("prints rates as 7.5% with no brackets, the format the form's VAT rows copy", () => {
    const out = text({ ...base({ name: "Ada Foods Ltd" }), lineItems: [{ description: "A", quantity: 1, unit_price: 10, vat_rate: 7.5, amount: 10 }] });
    expect(out).toContain("(7.5%)"); // PDF text operator wraps strings in brackets
    expect(out).not.toContain("(\\(7.5%\\))");
  });
});

describe("IVA-191 PDF VAT totals rows", () => {
  it("hides a ₦0.00 VAT totals row", () => {
    const out = text(base({ name: "Ada Foods Ltd" }));
    expect(out).not.toContain("NGN 0.00");
  });

  it("prints VAT 7.5% when every line uses the same rate", () => {
    const out = text({
      ...base({ name: "Ada Foods Ltd" }),
      lineItems: [{ description: "A", quantity: 1, unit_price: 1000, vat_rate: 7.5, amount: 1000 }],
      subtotal: 1000,
      vatAmount: 75,
      totalAmount: 1075,
    });
    expect(out).toContain("(VAT 7.5%)");
    expect(out).toContain("NGN 75.00");
  });

  it("prints one VAT row per rate when rates are mixed", () => {
    const out = text({
      ...base({ name: "Ada Foods Ltd" }),
      lineItems: [
        { description: "A", quantity: 1, unit_price: 1000, vat_rate: 7.5, amount: 1000 },
        { description: "B", quantity: 1, unit_price: 200, vat_rate: 5, amount: 200 },
      ],
      subtotal: 1200,
      vatAmount: 85,
      totalAmount: 1285,
    });
    expect(out).toContain("(VAT 7.5%)");
    expect(out).toContain("(VAT 5%)");
    expect(out).toContain("NGN 75.00");
    expect(out).toContain("NGN 10.00");
  });
});

