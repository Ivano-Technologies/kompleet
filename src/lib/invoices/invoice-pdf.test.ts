import { describe, expect, it } from "vitest";
import { deflateSync } from "node:zlib";
import { sniffImage } from "../../../convex/lib/imageMeta";
import { isAllowedLogoUrl, renderInvoicePdf, type InvoicePdfInput } from "./invoice-pdf";

function crc32(buf: Buffer): number {
  let c: number;
  let crc = 0xffffffff;
  for (let n = 0; n < buf.length; n++) {
    c = (crc ^ buf[n]!) & 0xff;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

/** Minimal solid grey RGB PNG. */
function png(width: number, height: number): Uint8Array {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  const raw = Buffer.alloc((width * 3 + 1) * height, 0x80);
  for (let y = 0; y < height; y++) raw[y * (width * 3 + 1)] = 0;
  return new Uint8Array(
    Buffer.concat([
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
      chunk("IHDR", ihdr),
      chunk("IDAT", deflateSync(raw)),
      chunk("IEND", Buffer.alloc(0)),
    ]),
  );
}

function base(sender: InvoicePdfInput["sender"], logo: InvoicePdfInput["logo"] = null): InvoicePdfInput {
  return {
    invoiceNumber: "INV-2026-0001",
    invoiceDate: "2026-10-17",
    dueDate: "2026-10-31",
    taxYear: 2026,
    customer: { name: "Bola Stores", address: "2 Allen Avenue\nIkeja, Lagos" },
    sender,
    lineItems: [{ description: "Catering", quantity: 2, unit_price: 50000, vat_rate: 0, amount: 100000 }],
    subtotal: 100000,
    vatAmount: 0,
    discountAmount: 0,
    totalAmount: 100000,
    logo,
  };
}

const text = (input: InvoicePdfInput) => renderInvoicePdf(input).output();

describe("IVA-185 invoice PDF", () => {
  it("footer is one line: Powered by Kompleet, with no NRS claim or tagline", () => {
    const out = text(base({ name: "Ada Foods Ltd" }));
    expect(out).toContain("Powered by Kompleet");
    expect(out).not.toMatch(/NRS/);
    expect(out).not.toMatch(/FIRS/);
    expect(out).not.toMatch(/Generated by/);
    expect(out).not.toMatch(/Kompleet records/);
    expect(out).not.toMatch(/Scan to verify/);
  });

  it("never prints KOMPLEET as the sender", () => {
    expect(text(base({ name: "Ada Foods Ltd" }))).not.toContain("KOMPLEET");
    expect(text(base({ name: "" }))).not.toContain("KOMPLEET");
  });

  it("name only prints the business name", () => {
    expect(text(base({ name: "Ada Foods Ltd" }))).toContain("Ada Foods Ltd");
  });

  it("no name prints the neutral placeholder", () => {
    expect(text(base({ name: "" }))).toContain("Your business name");
  });

  it("logo plus name embeds the image and prints the name", () => {
    const data = png(64, 64);
    const out = text(base({ name: "Ada Foods Ltd" }, { data, format: "PNG", width: 64, height: 64 }));
    expect(out).toContain("/Subtype /Image");
    expect(out).toContain("Ada Foods Ltd");
  });

  it("wide logo embeds the image and leaves the name out", () => {
    const data = png(400, 100);
    const out = text(base({ name: "Ada Foods Ltd" }, { data, format: "PNG", width: 400, height: 100 }));
    expect(out).toContain("/Subtype /Image");
    expect(out).not.toContain("Ada Foods Ltd");
  });

  it("has no green band or colour fills", () => {
    const out = text(base({ name: "Ada Foods Ltd" }));
    // #0A6847 as PDF rgb fill: 0.039 0.408 0.278
    expect(out).not.toMatch(/0\.039\d* 0\.408\d* 0\.278\d* rg/);
  });
});

describe("IVA-185 logo bytes", () => {
  it("reads PNG size", () => {
    expect(sniffImage(png(300, 120))).toEqual({ type: "image/png", width: 300, height: 120 });
  });

  it("rejects non images", () => {
    expect(sniffImage(new TextEncoder().encode("<svg onload=alert(1)>"))).toBeNull();
  });

  it("only fetches logos from Convex storage over https", () => {
    expect(isAllowedLogoUrl("https://shiny-cricket-316.convex.cloud/api/storage/x")).toBe(true);
    expect(isAllowedLogoUrl("http://shiny-cricket-316.convex.cloud/api/storage/x")).toBe(false);
    expect(isAllowedLogoUrl("https://169.254.169.254/latest")).toBe(false);
  });
});
